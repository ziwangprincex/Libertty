#!/usr/bin/env python3
"""Generate Sources/LiberttyApp/Input/KeyMap.swift: macOS virtual keycode -> GhosttyKey.

Source of truth is Ghostty's own table (src/input/keycodes.zig, columns
usb, evdev, xkb, win, mac, code), so our physical-key mapping matches
libghostty-vt's key encoder exactly.
"""
import pathlib, re

root = pathlib.Path(__file__).resolve().parent.parent
ghostty = root / "vendor/ghostty"
table = (ghostty / "src/input/keycodes.zig").read_text()
header = (ghostty / "include/ghostty/vt/key/event.h").read_text()

known = set(re.findall(r"\b(GHOSTTY_KEY_[A-Z0-9_]+)\b", header))
row = re.compile(r'\.\{\s*0x[0-9a-fA-F]+,\s*0x[0-9a-fA-F]+,\s*0x[0-9a-fA-F]+,\s*0x[0-9a-fA-F]+,\s*(0x[0-9a-fA-F]+),\s*"([A-Za-z0-9]*)"\s*\}')


def constant(code: str) -> str:
    if re.fullmatch(r"Key[A-Z]", code):
        return "GHOSTTY_KEY_" + code[3]
    snake = re.sub(r"(?<=[a-z])(?=[A-Z0-9])", "_", code)  # ArrowUp -> Arrow_Up, Digit0 -> Digit_0
    return "GHOSTTY_KEY_" + snake.upper()


entries = {}
for mac, code in row.findall(table):
    mac = int(mac, 16)
    if mac == 0xFFFF or not code:
        continue
    name = constant(code)
    if name in known and mac not in entries:
        entries[mac] = name

lines = [
    "// Generated by scripts/gen-keymap.py from vendor/ghostty/src/input/keycodes.zig. Do not edit.",
    "import CGhosttyVt",
    "",
    "/// macOS virtual keycode (`NSEvent.keyCode`) -> physical key for the libghostty-vt key encoder.",
    "let ghosttyKeyForKeyCode: [UInt16: GhosttyKey] = [",
]
lines += [f"    0x{mac:02x}: {name}," for mac, name in sorted(entries.items())]
lines += ["]", ""]

out = root / "Sources/LiberttyApp/Input/KeyMap.swift"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("\n".join(lines))
print(f"wrote {out.relative_to(root)} ({len(entries)} keys)")
